import json, os, sys, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WORKS = json.load(open(os.path.join(ROOT, "data", "works.json"), encoding="utf-8"))
BY_TITLE = {w["title"]: w for w in WORKS}

def norm(s):
    """归一化：只留汉字（去标点/数字/注释标记），容忍虚词与标点差异。"""
    return re.sub(r"[^一-龥]", "", s)

def find_para(work_title, keyword, occurrence=0):
    """在篇目中定位包含关键词的段落，返回 (段号从1起, 文本)。先精确后模糊。"""
    w = BY_TITLE.get(work_title)
    if not w:
        raise SystemExit("篇目不存在: %s" % work_title)
    hits = [i for i, p in enumerate(w["paragraphs"]) if keyword in p]
    if not hits:
        kw = norm(keyword)
        hits = [i for i, p in enumerate(w["paragraphs"]) if kw and kw in norm(p)]
    if not hits:
        raise SystemExit("关键词未命中 [%s / %s]" % (work_title, keyword))
    if occurrence >= len(hits):
        raise SystemExit("第%d次出现不存在 [%s / %s] 共%d次" % (occurrence, work_title, keyword, len(hits)))
    i = hits[occurrence]
    return i + 1, w["paragraphs"][i]

C = []  # concepts

def add(cid, name, category, oneliner, essence, quotes, evolution, related, qa):
    C.append({
        "id": cid, "name": name, "category": category,
        "oneliner": oneliner, "essence": essence,
        "quotes": quotes, "evolution": evolution,
        "related": related, "qa": qa,
    })

