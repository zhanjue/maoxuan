def main():
    works = load_works()
    items, seen = [], {}
    for wid, para, start, end, tag in SPEC:
        w = works[wid]
        text = cut(works, wid, para, start, end)
        key = "%s-p%d" % (wid, para)
        seen[key] = seen.get(key, 0) + 1
        # 同一段可能贡献多条（如 p6 两句矛盾论），id 必须唯一：段内再编号
        qid = key if seen[key] == 1 else "%s-%d" % (key, seen[key])
        items.append({
            "id": qid,
            "work": w["title"],
            "wid": wid,
            "period": w["period"],
            "date": w["date"],
            "para": para,
            "cue": text[:10],
            "tag": tag,
            "text": text,
        })
    # 按卷内篇目顺序、段号排序（书页顺序，不是按热度）
    order = {w["id"]: w["order"] for w in works.values()}
    items.sort(key=lambda x: (order[x["wid"]], x["para"]))

    out = {
        "note": "每条均为原文子串，按句截取，未改字。段号为 1 基，与阅读页显示一致；"
                "cue 是该段必含的原文片段，构建时逐条核对（段号会位移，锚词不会）。",
        "items": items,
    }
    path = os.path.join(DATA, "quotes.json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=2)
    print("写出 %d 条 -> %s" % (len(items), path))
    for it in items:
        print(" - %-8s p%-3d %-5s %s" % (it["wid"], it["para"], it["tag"],
                                         it["text"][:30] + ("…" if len(it["text"]) > 30 else "")))


if __name__ == "__main__":
    main()
