"""从 data/works.json 抽取「经典语录」页所需的短句。

原则（重要，不要为了好看去改字）：
1. 每条语录都是原文的子串，**逐字不改**，脚本里用 assert 硬校验。
2. 只做「按句截取」，不拼接不同段落，不改标点。
3. 每条都带篇目 id 与段号，页面上要能点回原文核对。

抽取方式：给定 (篇目id, 段号, 起始锚, 结束锚)，取 [起始锚, 结束锚] 之间的子串
（含结束锚）。锚点都是原文里现成的句子边界，避免手写整句时抄错一个字。

【段号口径】这里一律用 **1 基**，和阅读页 <div id="p1"> 的显示数字一致。
旧版脚本用 0 基下标取段落、又把下标当段号输出，导致每条语录显示的「第 N 段」
都比实际少 1，点过去落在上一段。已全部改为 1 基。

【cue 字段】每条同时输出 text 的前 10 个字作为锚词。段号会随数据清理整体位移
（清网页残留时全库前移过），锚词不会；构建时逐条核对，失配即报错退出。
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")


def load_works():
    with open(os.path.join(DATA, "works.json"), encoding="utf-8") as f:
        raw = json.load(f)
    works = raw if isinstance(raw, list) else raw.get("works") or raw.get("items")
    return {w["id"]: w for w in works}


def cut(works, wid, para, start, end):
    """para 为 1 基段号。从该段里截出 start..end（含两端），并校验是原文子串。"""
    w = works[wid]
    assert 1 <= para <= len(w["paragraphs"]), "段号越界：%s %s p%d" % (wid, w["title"], para)
    p = w["paragraphs"][para - 1]
    i = p.find(start)
    assert i >= 0, "起始锚不在原文里：%s / %s p%d / %r" % (wid, w["title"], para, start)
    j = p.find(end, i)
    assert j >= 0, "结束锚不在原文里：%s / %s p%d / %r" % (wid, w["title"], para, end)
    s = p[i:j + len(end)]
    assert s in p, "截取结果不是原文子串"
    return s


